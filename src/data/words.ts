/**
 * Get words by category
 */
export function getWordsByCategory(category: 'all' | 'top100' | 'top500' | 'top1000'): Word[] {
  if (category === 'all') return WORDS;
  return WORDS.filter((w) => w.category === category);
}

/**
 * Get word by ID
 */
export function getWordById(id: string): Word | undefined {
  return WORDS.find((w) => w.id === id);
}

/**
 * Get all word IDs for a category
 */
export function getWordIds(category: 'all' | 'top100' | 'top500' | 'top1000'): string[] {
  return getWordsByCategory(category).map((w) => w.id);
}
